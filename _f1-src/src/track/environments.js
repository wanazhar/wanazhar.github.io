/**
 * The profile for a circuit, with a safe default.
 *
 * Defaults matter: a circuit with no profile must still build a world, and it must build
 * a *generic* one rather than a broken one.
 *
 * @param {string} id
 */
export function environmentFor(id) {
  return (
    PROFILES[id] ?? {
      setting: SETTING.permanent,
      treeDensity: 0.5,
      buildingDensity: 0.15,
      groundTint: 0x74925a,
      dust: 0.1
    }
  );
}

/**
 * Does this setting put buildings hard against the track?
 *
 * A street circuit is not a permanent circuit with more scenery: the barrier is at the
 * edge of the road, there is effectively no run-off, and the buildings start
 * immediately behind it. That is the single biggest difference in how a circuit *feels*
 * to drive, and it should come from the data rather than from a hand-tuned constant per
 * circuit.
 *
 * @param {string} setting
 */
export function isStreet(setting) {
  return setting === SETTING.street;
}