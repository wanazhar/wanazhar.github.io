/**
 * Per-circuit identity.
 *
 * The centrelines are real, so the shape of each circuit is right. Everything *around*
 * it was generic: the same green, the same stands at the same spacing, the same run-off
 * everywhere. Two circuits that differ by a factor of three in width and are separated
 * by six thousand kilometres looked identical.
 *
 * This is the part that can be got right without visiting the circuits: what kind of
 * place each one is. A street circuit has buildings and walls pressed right up against
 * the barrier and almost no run-off. A parkland circuit has mature trees and houses set
 * back. A permanent circuit in the desert has none of either and a great deal of dust.
 *
 * ## Honesty about the data here
 *
 * Everything in this file is a **setting**, not a survey: what the circuit's surroundings
 * are, at the level of "street / parkland / permanent / desert" and what grows there.
 * That is a claim about the character of a place, and it is a claim that can be made
 * correctly from knowledge of the circuits.
 *
 * It is explicitly *not*:
 *
 * - **Elevation.** Spa's Raidillon and Monaco's climbs are the single most recognisable
 *   thing about both circuits, and neither is modelled. The centres are all at y = 0.
 *   Real elevation needs real survey data -- OSM `ele` tags per node, or a DEM -- and
 *   inventing plausible-looking numbers would be worse than leaving it flat, because a
 *   wrong hill changes the driving as well as the view.
 * - **Corner-by-corner furniture.** Real circuits put gravel traps, kerbs and
 *   barriers in specific places because of specific terrain. The layouts here are
 *   generated by character, not surveyed.
 *
 * Both are listed in the README as known limitations for exactly this reason.
 */

/** How the circuit sits in its surroundings. */
